def probe(tool, **kw):
    args = [f'{k}={json.dumps(v)}' for k, v in kw.items()]
    r = subprocess.run([sys.executable, "../../session_tools/tool_probe.py", tool] + args,
                       capture_output=True, text=True, timeout=400)
    out = r.stdout
    i = out.find("[")
    j = out.find("{")
    start = min(x for x in (i, j) if x >= 0) if (i>=0 or j>=0) else -1
    if start < 0:
        print("NO JSON:", out[:300], r.stderr[:300]); return []
    try:
        data = json.loads(out[start:])
    except Exception as e:
        print("PARSE FAIL", e, out[:200]); return []
    return data

queries = ["DistilBERT", "DistilBERT baseline", "DistilBERT smaller faster",
           "distilled version of BERT", "DistilBERT knowledge distillation",
           "DistilBERT fine-tuned", "compared with DistilBERT", "DistilBERT model efficient"]
all_cids = set()
for q in queries:
    data = probe("snippet_search", query=q, limit=100)
    # flatten: wrapper {"data": [...]}
    entries = []
    if isinstance(data, dict) and "data" in data: entries = data["data"]
    elif isinstance(data, list):
        for d in data:
            if isinstance(d, dict) and "data" in d: entries.extend(d["data"])
    cids = set()
    for e in entries:
        p = (e or {}).get("paper") or {}
        c = str(p.get("corpusId") or "")
        if c: cids.add(c)
    hit = cids & GOLD
    all_cids |= cids
    print(f"q={q!r}: {len(entries)} passages, {len(cids)} papers, {len(hit)} gold")
